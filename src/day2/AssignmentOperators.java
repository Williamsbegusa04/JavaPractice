package day2;

public class AssignmentOperators
{
    public static void main(String[] args)
    {
        //assignment operators =  +=  -=  *=  /=  %=
        //case1
        int a = 10;
        a+=5; //a=a+5
        System.out.println(a);

        //case2
        int b = 10;
        b-=5; //b=b-5
        System.out.println(b);

        //case3
        int c = 10;
        c*=5; //c=c*5
        System.out.println(c);

        //case4
        int d = 10;
        d/=5; //d=d/5
        System.out.println(d);

        //case5
        int e = 10;
        e%=5; //e=e%5
        System.out.println(e);


    }
}
